def glyph_rows(char: str) -> tuple[int, ...]:
    """Return the bit rows of a character; each row has 7 usable bits."""
    if char == " ":
        return (0,) * GLYPH_HEIGHT
    encoded = GLYPHS.get(char, GLYPHS[FALLBACK_CHAR])
    return tuple(bytes.fromhex(encoded))
